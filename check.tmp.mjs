import { chromium } from 'playwright-core'
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--headless=new'] })
const p = await b.newPage({ viewport: { width: 1400, height: 1000 } })
const errs = []; p.on('pageerror', e => errs.push(String(e)))
p.on('console', m => m.type()==='error' && !/ERR_CONNECTION/.test(m.text()) && errs.push(m.text()))
await p.goto('http://localhost:4173/?view=backtesting', { waitUntil: 'networkidle' })
await p.waitForTimeout(1000)
await p.locator('input[type="file"]').first().setInputFiles('/tmp/eurusd.csv'); await p.waitForTimeout(1500)
const toggle = p.locator('button', { hasText: /^off$/ }).first()
console.log('toggle found:', await toggle.count())
await toggle.scrollIntoViewIfNeeded(); await toggle.click(); await p.waitForTimeout(1200)
const txt = await p.evaluate(()=>document.body.textContent)
const j = txt.indexOf('ICT / SMC')
console.log('PANEL:\n' + (j<0?'[MISSING]':txt.slice(j, j+700)))
// overlays drawn?
console.log('svg rects:', await p.locator('svg rect').count())
console.log('svg dashed lines:', await p.evaluate(()=>document.querySelectorAll('svg line[stroke-dasharray]').length))
// step forward and confirm it recomputes without error
const nextBtn = () => p.locator('button', { hasText: /^›$|Next|Step/ }).first()
for (let i=0;i<25;i++){ await nextBtn().click(); await p.waitForTimeout(25) }
await p.waitForTimeout(500)
const t2 = await p.evaluate(()=>document.body.textContent)
const k = t2.indexOf('Confluence')
console.log('AFTER STEPPING:\n' + (k<0?'[no confluence block — bias unset]':t2.slice(k, k+330)))
console.log('OVERFLOW:', await p.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth))
await p.setViewportSize({width:390,height:800}); await p.waitForTimeout(600)
console.log('MOBILE OVERFLOW:', await p.evaluate(()=>document.documentElement.scrollWidth-document.documentElement.clientWidth))
console.log('ERRORS:', errs.slice(0,2))
await b.close()
